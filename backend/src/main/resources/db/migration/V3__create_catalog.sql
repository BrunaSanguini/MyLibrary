-- Classification of the collection (docs/modelo-de-dados.md, books module).
-- normalized_name: lowercase, without accents and with single spaces (TextNormalizer).

CREATE TABLE author (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name            VARCHAR(200)             NOT NULL,
    normalized_name VARCHAR(200)             NOT NULL,
    ol_author_key   VARCHAR(32),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_author PRIMARY KEY (id),
    CONSTRAINT uk_author_ol_author_key UNIQUE (ol_author_key)
);

-- Two authors may share a name, so the index is not unique.
CREATE INDEX ix_author_normalized_name ON author (normalized_name);

CREATE TABLE publisher (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name            VARCHAR(200)             NOT NULL,
    normalized_name VARCHAR(200)             NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_publisher PRIMARY KEY (id),
    CONSTRAINT uk_publisher_normalized_name UNIQUE (normalized_name)
);

CREATE TABLE series (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name            VARCHAR(200)             NOT NULL,
    normalized_name VARCHAR(200)             NOT NULL,
    total_volumes   INT,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_series PRIMARY KEY (id),
    CONSTRAINT uk_series_normalized_name UNIQUE (normalized_name),
    CONSTRAINT ck_series_total_volumes CHECK (total_volumes IS NULL OR total_volumes > 0)
);

-- A genre has no parent; a subgenre points to a genre. The two-level rule lives in the service.
CREATE TABLE genre (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name            VARCHAR(100)             NOT NULL,
    normalized_name VARCHAR(100)             NOT NULL,
    parent_id       BIGINT,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_genre PRIMARY KEY (id),
    CONSTRAINT uk_genre_normalized_name UNIQUE (normalized_name),
    CONSTRAINT fk_genre_parent FOREIGN KEY (parent_id) REFERENCES genre (id),
    CONSTRAINT ck_genre_parent CHECK (parent_id IS NULL OR parent_id <> id)
);
