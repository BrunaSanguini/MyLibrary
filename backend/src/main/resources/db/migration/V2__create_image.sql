-- Images saved on disk under images/{kind}/{file_name} (docs/modelo-de-dados.md).
-- A row never changes: replacing a cover creates a new image.
CREATE TABLE image (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    kind         VARCHAR(8)               NOT NULL,
    file_name    VARCHAR(100)             NOT NULL,
    content_type VARCHAR(20)              NOT NULL,
    size_bytes   INT                      NOT NULL,
    sha256       CHAR(64)                 NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_image PRIMARY KEY (id),
    CONSTRAINT uk_image_file_name UNIQUE (file_name),
    CONSTRAINT ck_image_kind CHECK (kind IN ('COVER', 'BANNER', 'AVATAR')),
    CONSTRAINT ck_image_content_type CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
    CONSTRAINT ck_image_size_bytes CHECK (size_bytes > 0)
);

ALTER TABLE profile
    ADD CONSTRAINT fk_profile_avatar_image FOREIGN KEY (avatar_image_id) REFERENCES image (id) ON DELETE SET NULL;
