-- The books featured on the Home, one to three in order, each with an image of its own (docs/modelo-de-dados.md).
-- The image belongs to the slot, not to the book: changing the book of a slot keeps its image.
CREATE TABLE featured_book (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    slot       SMALLINT                 NOT NULL,
    book_id    BIGINT                   NOT NULL,
    image_id   BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_featured_book PRIMARY KEY (id),
    CONSTRAINT uk_featured_book_slot UNIQUE (slot),
    CONSTRAINT ck_featured_book_slot CHECK (slot BETWEEN 1 AND 3),
    CONSTRAINT fk_featured_book_book FOREIGN KEY (book_id) REFERENCES book (id) ON DELETE CASCADE,
    CONSTRAINT fk_featured_book_image FOREIGN KEY (image_id) REFERENCES image (id) ON DELETE SET NULL
);
