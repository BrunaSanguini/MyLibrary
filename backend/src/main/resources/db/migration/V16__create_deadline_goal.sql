-- Goals with a deadline (docs/modelo-de-dados.md, goals module): a target between two dates chosen by the reader,
-- optionally only for the books of one genre and its subgenres. Deleting the genre deletes the goal, which would
-- otherwise start counting every book without saying so.

CREATE TABLE deadline_goal (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    type       VARCHAR(10)              NOT NULL,
    target     INT                      NOT NULL,
    start_date DATE                     NOT NULL,
    end_date   DATE                     NOT NULL,
    genre_id   BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_deadline_goal PRIMARY KEY (id),
    CONSTRAINT ck_deadline_goal_type CHECK (type IN ('BOOKS', 'PAGES', 'REREADS')),
    CONSTRAINT ck_deadline_goal_target CHECK (target > 0),
    CONSTRAINT ck_deadline_goal_dates CHECK (end_date >= start_date),
    CONSTRAINT fk_deadline_goal_genre FOREIGN KEY (genre_id) REFERENCES genre (id) ON DELETE CASCADE
);

CREATE INDEX ix_deadline_goal_genre ON deadline_goal (genre_id);
