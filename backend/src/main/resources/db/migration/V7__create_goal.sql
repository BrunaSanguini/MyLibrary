CREATE TABLE goal (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    type         VARCHAR(10)              NOT NULL,
    period       VARCHAR(5)               NOT NULL,
    period_year  SMALLINT                 NOT NULL,
    period_month SMALLINT,
    target       INT                      NOT NULL,
    -- Two NULLs are different to UNIQUE, so yearly goals would repeat freely. The key turns "no month"
    -- into 0 and lets one constraint cover yearly and monthly goals.
    period_key   SMALLINT GENERATED ALWAYS AS (COALESCE(period_month, 0)),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_goal PRIMARY KEY (id),
    CONSTRAINT uk_goal_type_period UNIQUE (type, period_year, period_key),
    CONSTRAINT ck_goal_type CHECK (type IN ('BOOKS', 'PAGES', 'REREADS')),
    CONSTRAINT ck_goal_period CHECK (
        (period = 'YEAR' AND period_month IS NULL)
            OR (period = 'MONTH' AND period_month BETWEEN 1 AND 12)
    ),
    CONSTRAINT ck_goal_rereads_by_year CHECK (type <> 'REREADS' OR period = 'YEAR'),
    CONSTRAINT ck_goal_target CHECK (target > 0)
);
