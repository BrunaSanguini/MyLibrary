-- An edition of a book and its links to the catalog (docs/modelo-de-dados.md, books module).
-- search_text: title and subtitle normalized (TextNormalizer), recalculated by the entity on every save.

CREATE TABLE book (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    title           VARCHAR(500)             NOT NULL,
    subtitle        VARCHAR(500),
    isbn13          CHAR(13),
    isbn10          CHAR(10),
    page_count      INT,
    published_year  SMALLINT,
    language_code   VARCHAR(3),
    synopsis        VARCHAR(10000),
    ownership       VARCHAR(10)              NOT NULL,
    favorite        BOOLEAN                  NOT NULL,
    publisher_id    BIGINT,
    series_id       BIGINT,
    series_position DECIMAL(4, 1),
    cover_image_id  BIGINT,
    banner_image_id BIGINT,
    ol_work_key     VARCHAR(32),
    ol_edition_key  VARCHAR(32),
    search_text     VARCHAR(1001)            NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_book PRIMARY KEY (id),
    CONSTRAINT uk_book_isbn13 UNIQUE (isbn13),
    CONSTRAINT uk_book_ol_edition_key UNIQUE (ol_edition_key),
    CONSTRAINT fk_book_publisher FOREIGN KEY (publisher_id) REFERENCES publisher (id) ON DELETE SET NULL,
    -- Without cascade: deleting a series clears series_id and series_position together (SeriesService),
    -- so no book is ever left with a position and no series.
    CONSTRAINT fk_book_series FOREIGN KEY (series_id) REFERENCES series (id),
    CONSTRAINT fk_book_cover_image FOREIGN KEY (cover_image_id) REFERENCES image (id) ON DELETE SET NULL,
    CONSTRAINT fk_book_banner_image FOREIGN KEY (banner_image_id) REFERENCES image (id) ON DELETE SET NULL,
    CONSTRAINT ck_book_page_count CHECK (page_count IS NULL OR page_count > 0),
    CONSTRAINT ck_book_ownership CHECK (ownership IN ('OWNED', 'WISHLIST', 'NONE')),
    CONSTRAINT ck_book_series_position CHECK (
        (series_id IS NULL AND series_position IS NULL)
            OR (series_id IS NOT NULL AND series_position IS NOT NULL AND series_position > 0)
    )
);

-- Shelf search compares the normalized term with search_text.
CREATE INDEX ix_book_search_text ON book (search_text);
CREATE INDEX ix_book_series ON book (series_id, series_position);

-- author_order keeps the order printed on the cover.
CREATE TABLE book_author (
    book_id      BIGINT   NOT NULL,
    author_id    BIGINT   NOT NULL,
    author_order SMALLINT NOT NULL,
    CONSTRAINT pk_book_author PRIMARY KEY (book_id, author_id),
    CONSTRAINT fk_book_author_book FOREIGN KEY (book_id) REFERENCES book (id) ON DELETE CASCADE,
    CONSTRAINT fk_book_author_author FOREIGN KEY (author_id) REFERENCES author (id),
    CONSTRAINT ck_book_author_order CHECK (author_order >= 0)
);

CREATE INDEX ix_book_author_author ON book_author (author_id);

CREATE TABLE book_genre (
    book_id  BIGINT NOT NULL,
    genre_id BIGINT NOT NULL,
    CONSTRAINT pk_book_genre PRIMARY KEY (book_id, genre_id),
    CONSTRAINT fk_book_genre_book FOREIGN KEY (book_id) REFERENCES book (id) ON DELETE CASCADE,
    CONSTRAINT fk_book_genre_genre FOREIGN KEY (genre_id) REFERENCES genre (id) ON DELETE CASCADE
);

CREATE INDEX ix_book_genre_genre ON book_genre (genre_id);
