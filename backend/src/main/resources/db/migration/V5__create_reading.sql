-- Readings, their daily sessions and the review of each book (docs/modelo-de-dados.md, reading module).

CREATE TABLE reading (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    book_id             BIGINT                   NOT NULL,
    status              VARCHAR(12)              NOT NULL,
    start_date          DATE,
    end_date            DATE,
    reread              BOOLEAN                  NOT NULL,
    -- H2 has no partial index, so "at most one reading in progress per book" is this column: it holds
    -- the book only while the reading is in progress, and UNIQUE ignores the nulls of the others.
    in_progress_book_id BIGINT GENERATED ALWAYS AS (CASE WHEN status = 'IN_PROGRESS' THEN book_id END),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_reading PRIMARY KEY (id),
    CONSTRAINT fk_reading_book FOREIGN KEY (book_id) REFERENCES book (id) ON DELETE CASCADE,
    CONSTRAINT uk_reading_in_progress UNIQUE (in_progress_book_id),
    CONSTRAINT ck_reading_status CHECK (status IN ('IN_PROGRESS', 'FINISHED', 'ABANDONED')),
    -- In progress: started and not ended. Finished or abandoned: ended; old readings may lack the start.
    CONSTRAINT ck_reading_period CHECK (
        (status = 'IN_PROGRESS' AND start_date IS NOT NULL AND end_date IS NULL)
            OR (status <> 'IN_PROGRESS' AND end_date IS NOT NULL)
    ),
    CONSTRAINT ck_reading_end_after_start CHECK (
        start_date IS NULL OR end_date IS NULL OR end_date >= start_date
    )
);

-- The shelf looks for the latest reading of each book.
CREATE INDEX ix_reading_book ON reading (book_id, status, end_date);

CREATE TABLE reading_session (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reading_id   BIGINT                   NOT NULL,
    session_date DATE                     NOT NULL,
    pages_read   INT                      NOT NULL,
    note         VARCHAR(2000),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_reading_session PRIMARY KEY (id),
    CONSTRAINT fk_reading_session_reading FOREIGN KEY (reading_id) REFERENCES reading (id) ON DELETE CASCADE,
    CONSTRAINT ck_reading_session_pages CHECK (pages_read > 0)
);

CREATE INDEX ix_reading_session_reading ON reading_session (reading_id, session_date);
-- Goals and statistics add up the pages of a period.
CREATE INDEX ix_reading_session_date ON reading_session (session_date);

CREATE TABLE review (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    book_id    BIGINT                   NOT NULL,
    rating     DECIMAL(2, 1),
    content    VARCHAR(20000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_review PRIMARY KEY (id),
    CONSTRAINT fk_review_book FOREIGN KEY (book_id) REFERENCES book (id) ON DELETE CASCADE,
    CONSTRAINT uk_review_book UNIQUE (book_id),
    -- From 1 to 5 in half points: twice the rating is a whole number.
    CONSTRAINT ck_review_rating CHECK (
        rating IS NULL OR (rating BETWEEN 1 AND 5 AND rating * 2 = FLOOR(rating * 2))
    ),
    CONSTRAINT ck_review_not_empty CHECK (rating IS NOT NULL OR content IS NOT NULL)
);

CREATE INDEX ix_review_updated_at ON review (updated_at);
