-- Lists of books made by the user (docs/modelo-de-dados.md, lists module).

CREATE TABLE book_list (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name            VARCHAR(120)             NOT NULL,
    normalized_name VARCHAR(120)             NOT NULL,
    description     VARCHAR(1000),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_book_list PRIMARY KEY (id),
    CONSTRAINT uk_book_list_normalized_name UNIQUE (normalized_name)
);

-- item_order is the position the user gave the book in the list; it may have gaps after a removal.
CREATE TABLE book_list_item (
    book_list_id BIGINT                   NOT NULL,
    book_id      BIGINT                   NOT NULL,
    item_order   INT                      NOT NULL,
    added_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_book_list_item PRIMARY KEY (book_list_id, book_id),
    CONSTRAINT fk_book_list_item_list FOREIGN KEY (book_list_id) REFERENCES book_list (id) ON DELETE CASCADE,
    CONSTRAINT fk_book_list_item_book FOREIGN KEY (book_id) REFERENCES book (id) ON DELETE CASCADE,
    CONSTRAINT ck_book_list_item_order CHECK (item_order >= 0)
);

CREATE INDEX ix_book_list_item_book ON book_list_item (book_id);
