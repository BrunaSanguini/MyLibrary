package io.github.brunasanguini.minhalivraria;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.test.web.servlet.assertj.MockMvcTester;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/**
 * Keeps docs/openapi.json equal to the contract generated by the code (ADR-0005). The generated version is always
 * written to target/openapi.json; run with {@code -Dopenapi.update=true} to update the versioned file.
 */
@SpringBootTest
@AutoConfigureMockMvc
class OpenApiContractTest {

    private static final Path SNAPSHOT = Path.of("..", "docs", "openapi.json");
    private static final Path GENERATED = Path.of("target", "openapi.json");
    private static final String UPDATE_COMMAND = "./mvnw test -Dtest=OpenApiContractTest -Dopenapi.update=true";

    private final JsonMapper json = JsonMapper.builder().build();

    @Autowired
    private MockMvcTester mvc;

    @Test
    void shouldMatchTheVersionedContract() throws IOException {
        String body = mvc.get().uri("/v3/api-docs").exchange().getResponse().getContentAsString(StandardCharsets.UTF_8);
        JsonNode generated = json.readTree(body);
        String pretty = json.writerWithDefaultPrettyPrinter().writeValueAsString(generated) + "\n";
        Files.writeString(GENERATED, pretty);

        if (Boolean.getBoolean("openapi.update")) {
            Files.writeString(SNAPSHOT, pretty);
            return;
        }

        assertThat(SNAPSHOT).as("docs/openapi.json não existe. Gere com: " + UPDATE_COMMAND).exists();
        assertThat(json.readTree(Files.readString(SNAPSHOT)))
                .as("docs/openapi.json está desatualizado. Atualize com: " + UPDATE_COMMAND)
                .isEqualTo(generated);
    }
}
